/**
 * Generate src/lib/font-data.ts berisi base64 string untuk semua font
 * di public/fonts/. File ini akan di-import oleh quotes.ts sehingga
 * font ter-bundle di serverless function (Vercel Lambda).
 */
const fs = require('fs');
const path = require('path');

const fontsDir = path.join(__dirname, '..', 'public', 'fonts');
const outFile = path.join(__dirname, '..', 'src', 'lib', 'font-data.ts');

const fonts = [
  { name: 'SERIF_REGULAR',   file: 'LiberationSerif-Regular.ttf' },
  { name: 'SERIF_BOLD',      file: 'LiberationSerif-Bold.ttf' },
  { name: 'SERIF_ITALIC',    file: 'LiberationSerif-Italic.ttf' },
  { name: 'SANS_REGULAR',    file: 'Carlito-Regular.ttf' },
  { name: 'SANS_BOLD',       file: 'Carlito-Bold.ttf' },
  { name: 'SANS_ITALIC',     file: 'Carlito-Italic.ttf' },
];

const lines = [
  '/**',
  ' * AUTO-GENERATED by scripts/gen-font-base64.js',
  ' * Berisi base64 string untuk semua font yang dipakai di SVG.',
  ' * Di-import oleh quotes.ts agar ter-bundle di serverless function.',
  ' */',
  '',
];

for (const f of fonts) {
  const fp = path.join(fontsDir, f.file);
  if (!fs.existsSync(fp)) {
    console.error(`MISSING: ${fp}`);
    continue;
  }
  const buf = fs.readFileSync(fp);
  const b64 = buf.toString('base64');
  const sizeKB = (buf.length / 1024).toFixed(1);
  console.log(`  ${f.file}: ${sizeKB} KB -> base64 ${b64.length} chars`);
  lines.push(`export const ${f.name} = "${b64}";`);
  lines.push('');
}

fs.writeFileSync(outFile, lines.join('\n'));
console.log(`\nWrote: ${outFile}`);
console.log(`Total size: ${(fs.readFileSync(outFile).length / 1024).toFixed(1)} KB`);
